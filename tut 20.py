print("A random number is generated by computer,Guess the number \n")
num = 19
guess_left = 9
print("Only 9 guesses are there\n")

while(True):                                                     # WILL COME BACK TO HERE <<--------------------------------------|
    inpNum = int(input("Enter the number:"))                                                                            #   #     |
    guess_left = guess_left - 1                                                                                         #   #     |
    if inpNum < num:                                                                                                    #   #     |
        print("Entered number is less than generated number")                                                           #   #     |
        print("No of guesses left:",guess_left, "\n")                                                                   #   #     |
        continue                                                            # ------------------------------------------------>>  |
    if inpNum > num:                                                                                                    #   #     |
        print("Entered number is greater than generated number")                                                        #   #     |
        print("No of guesses left:", guess_left, "\n")                                                                  #   #     |
        continue                                                            # ------------------------------------------------>>  |
    if inpNum == num:
        print("Entered number is equal to generated number\n")
        print("YOU WON")
        print("No of guesses took to win:", 9 - guess_left, "\n")
        break